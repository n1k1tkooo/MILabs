import { ModelProvider, RegulationCitation, DocumentMeta, CurrentUser } from '../types';

export interface RAGAnswerResult {
  text: string;
  citations: RegulationCitation[];
  isConfidentialWarning: boolean;
  modelUsed: ModelProvider;
}

/**
 * Локальный симулятор RAG-пайплайна
 * Выполняет семантический матчинг, фильтрацию RBAC по 152-ФЗ и генерацию ответа с цитированием
 */
export function simulateRAGQuery(
  query: string,
  user: CurrentUser,
  model: ModelProvider,
  documents: DocumentMeta[]
): RAGAnswerResult {
  const cleanQuery = query.toLowerCase().trim();

  // 1. Проверка на запрос конфиденциальных данных без допуска
  if (cleanQuery.includes('зарплат') || cleanQuery.includes('компенсац') || cleanQuery.includes('директор')) {
    if (user.role === 'user') {
      return {
        text: 'В доступных вам нормативных документах информация по данному вопросу отсутствует или относится к уровню ограниченного доступа (Коммерческая тайна / 152-ФЗ). Обратитесь к вашему руководителю или офицеру безопасности.',
        citations: [],
        isConfidentialWarning: true,
        modelUsed: model,
      };
    }
  }

  // 2. Тематический матчинг: VPN / IT
  if (cleanQuery.includes('vpn') || cleanQuery.includes('впн') || cleanQuery.includes('удален')) {
    return {
      text: `Для подключения к внутренним ресурсам компании согласно "Инструкции по настройке VPN v1.5":

1. **Клиент:** Установите корпоративный WireGuard или OpenVPN клиент.
2. **Двухфакторная аутентификация (2FA):** Получите одноразовый конфигурационный профиль в IT-Helpdesk и подключите приложение Яндекс.Ключ / Google Authenticator.
3. **Безопасность:** Запрещается сохранение пароля учетной записи в открытом виде на личных устройствах.`,
      citations: [
        {
          citationId: 'cit-1',
          docId: 'DOC-IT-01',
          docTitle: 'Инструкция по настройке двухфакторного VPN для удаленной работы',
          article: 'Статья 2.1 (Сетевой доступ)',
          department: 'IT & Разработка',
          quote: 'Подключение к внутренним контурам компании разрешено исключительно с использованием корпоративного двухфакторного VPN-клиента.',
          accessLevel: 'public',
        },
      ],
      isConfidentialWarning: false,
      modelUsed: model,
    };
  }

  // 3. Тематический матчинг: 152-ФЗ и персональные данные
  if (cleanQuery.includes('152') || cleanQuery.includes('персональн') || cleanQuery.includes('данны')) {
    return {
      text: `Порядок обработки персональных данных строго регламентирован Федеральным законом № 152-ФЗ и внутренней Политикой компании:

1. **Локализация баз данных:** Все базы данных с ПДн клиентов и сотрудников размещаются строго на серверах внутри территории Российской Федерации.
2. **Запрет на публичные LLM:** Категорически запрещена загрузка документов с персональными данными (ФИО, телефоны, паспортные данные) в незащищенные сторонние чат-боты.
3. **Согласие субъекта:** Любая обработка данных кандидатов и клиентов требует наличия подписанного письменного или электронного согласия.`,
      citations: [
        {
          citationId: 'cit-2',
          docId: 'DOC-SEC-02',
          docTitle: 'Политика обработки персональных данных согласно 152-ФЗ РФ',
          article: 'Статья 4, Пункт 1.2',
          department: 'Информационная Безопасность',
          quote: 'Обработка персональных данных осуществляется исключительно на защищенных серверах на территории РФ с обязательным шифрованием каналов передачи.',
          accessLevel: 'public',
        },
      ],
      isConfidentialWarning: false,
      modelUsed: model,
    };
  }

  // 4. Тематический матчинг: Отпуск / HR
  if (cleanQuery.includes('отпуск') || cleanQuery.includes('больничн') || cleanQuery.includes('hr')) {
    return {
      text: `Согласно "Порядку предоставления отпусков v2.0":

1. **Сроки подачи заявления:** Заявление на ежегодный оплачиваемый отпуск подается не позднее, чем за 14 календарных дней до предполагаемой даты начала через личный кабинет.
2. **Дробитность:** Хотя бы одна из частей отпуска должна составлять не менее 14 календарных дней.
3. **Учебный отпуск:** Предоставляется на основании справки-вызова из аккредитованного учебного заведения с сохранением среднего заработка.`,
      citations: [
        {
          citationId: 'cit-3',
          docId: 'DOC-HR-01',
          docTitle: 'Порядок предоставления основных и учебных отпусков',
          article: 'Раздел 3, п. 3.4',
          department: 'Кадры и HR',
          quote: 'Заявление на отпуск подается сотрудником не менее чем за две недели до начала периода для своевременного начисления выплат.',
          accessLevel: 'public',
        },
      ],
      isConfidentialWarning: false,
      modelUsed: model,
    };
  }

  // 5. Защита от галлюцинаций (Edge Case: отсутствие совпадений)
  return {
    text: 'В действующих регламентах и инструкциях компании нет информации по данному вопросу. Пожалуйста, уточните формулировку или обратитесь в соответствующий департамент компании.',
    citations: [],
    isConfidentialWarning: false,
    modelUsed: model,
  };
}
