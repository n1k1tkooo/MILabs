def inspect_dlp_payload(text: str, policy: str = "redact") -> dict:
    """
    Инспектор предотвращения утечек персональных и конфиденциальных данных (152-ФЗ / ФСТЭК).
    Распознает паспорта РФ, СНИЛС, банковские карты МИР/Visa, API-ключи, ДСП и ИНН.
    """
    findings = []
    sanitized = text
    risk_score = 0

    # 1. Паспорт гражданина РФ
    passport_pattern = re.compile(r'(?i)(?:паспорт(?:\s*рф|\s*гражданина)?\s*[:№]?\s*)?(\b\d{2}\s*\d{2}\b)\s*[- ]?(\b\d{6}\b)')
    for m in passport_pattern.finditer(text):
        matched_str = m.group(0)
        findings.append({
            "type": "passport_rf",
            "label": "Паспорт гражданина РФ",
            "match": matched_str,
            "severity": "CRITICAL",
            "law": "152-ФЗ ст. 10 (Специальные категории ПДн)",
            "start": m.start(),
            "end": m.end()
        })
        risk_score += 35
        sanitized = sanitized.replace(matched_str, "[ЗАМАСКИРОВАНО: Паспорт РФ ** ** ******]")

    # 2. СНИЛС (XXX-XXX-XXX YY)
    snils_pattern = re.compile(r'\b(\d{3})[- ](\d{3})[- ](\d{3})[- ](\d{2})\b')
    for m in snils_pattern.finditer(text):
        matched_str = m.group(0)
        findings.append({
            "type": "snils",
            "label": "Страховой номер СНИЛС",
            "match": matched_str,
            "severity": "CRITICAL",
            "law": "152-ФЗ ст. 19 (Идентификатор субъекта ПДн)",
            "start": m.start(),
            "end": m.end()
        })
        risk_score += 35
        sanitized = sanitized.replace(matched_str, f"[ЗАМАСКИРОВАНО: СНИЛС ***-***-*** {m.group(4)}]")

    # 3. Банковские карты (МИР 2200-2204, Visa 4xxx, MC 5xxx)
    card_pattern = re.compile(r'\b(220[0-4]|4\d{3}|5[1-5]\d{2})[- ]?(\d{4})[- ]?(\d{4})[- ]?(\d{4})\b')
    for m in card_pattern.finditer(text):
        matched_str = m.group(0)
        card_type = "МИР (НСПК)" if m.group(1).startswith("220") else "Банковская карта"
        findings.append({
            "type": "bank_card",
            "label": f"Номер карты {card_type}",
            "match": matched_str,
            "severity": "CRITICAL",
            "law": "161-ФЗ О национальной платежной системе / PCI DSS",
            "start": m.start(),
            "end": m.end()
        })
        risk_score += 40
        sanitized = sanitized.replace(matched_str, f"[ЗАМАСКИРОВАНО: Карта {card_type} {m.group(1)} **** **** {m.group(4)}]")

    # 4. API-ключи, токены и секреты
    secret_pattern = re.compile(r'(?i)(?:api[_-]?key|secret|token|bearer|yandex_gpt_secret|auth_token)\s*[:=]\s*["\']?([a-zA-Z0-9_\-\.]{12,})["\']?')
    for m in secret_pattern.finditer(text):
        matched_str = m.group(0)
        secret_val = m.group(1)
        findings.append({
            "type": "api_secret",
            "label": "API-ключ / Секретный токен доступа",
            "match": matched_str,
            "severity": "HIGH",
            "law": "Приказ ФСТЭК № 21 (Защита аутентификационных данных)",
            "start": m.start(),
            "end": m.end()
        })
        risk_score += 30
        sanitized = sanitized.replace(secret_val, "************************")

    # 5. Гриф ДСП и чувствительные зарплатные данные
    dsp_pattern = re.compile(r'(?i)(?:гриф\s*:\s*дсп|зарплатн\w+\s+ведомост\w+|оклад\w+\s+(?:топ-менеджмент\w+|руководств\w+|директор\w+)|премиальн\w+\s+фонд\w+|коммерческ\w+\s+тайн\w+)')
    for m in dsp_pattern.finditer(text):
        matched_str = m.group(0)
        findings.append({
            "type": "dsp_confidential",
            "label": "Коммерческая тайна / Конфиденциальные данные ДСП",
            "match": matched_str,
            "severity": "HIGH",
            "law": "98-ФЗ О коммерческой тайне / Внутренний регламент SEC-03",
            "start": m.start(),
            "end": m.end()
        })
        risk_score += 25
        sanitized = sanitized.replace(matched_str, "[КОНФИДЕНЦИАЛЬНО: ДСП ЗАБЛОКИРОВАНО]")

    # 6. ИНН
    inn_pattern = re.compile(r'(?i)(?:инн\s*[:№]?\s*)(\d{10}|\d{12})\b')
    for m in inn_pattern.finditer(text):
        matched_str = m.group(0)
        findings.append({
            "type": "inn",
            "label": "Идентификационный номер налогоплательщика (ИНН)",
            "match": matched_str,
            "severity": "MEDIUM",
            "law": "152-ФЗ ст. 9 (Иные категории ПДн)",
            "start": m.start(),
            "end": m.end()
        })
        risk_score += 15
        sanitized = sanitized.replace(m.group(1), "**********")

    risk_score = min(100, risk_score)
    if risk_score == 0:
        risk_level = "SAFE"
    elif risk_score <= 30:
        risk_level = "LOW"
    elif risk_score <= 65:
        risk_level = "HIGH"
    else:
        risk_level = "CRITICAL"

    is_blocked = (policy == "quarantine" and risk_score >= 30)
    action = "quarantined" if is_blocked else ("redacted" if findings else "allowed")

    return {
        "risk_score": risk_score,
        "risk_level": risk_level,
        "findings_count": len(findings),
        "findings": findings,
        "sanitized_text": sanitized,
        "action": action,
        "is_blocked": is_blocked,
        "policy": policy,
        "timestamp": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    }


